/* Bounded, allowlisted crash summaries, produced before RAM /data can vanish.
 * The Android shell runs in the existing diagnostic domain, never in PID1.
 * Paths/argv/PIDs/registers/memory/exception text are not written to the store.
 */
static const char crash_script[] =
    "PATH=/system/bin:/system/xbin\n"
    "export PATH\n"
    "set -o pipefail\n"
    "ready=0; [ -d /data/tombstones ] && [ -d /data/anr ] && ready=1\n"
    "running=0; [ \"$(getprop init.svc.tombstoned)\" = running ] && running=1\n"
    "dump64=0; [ -x /apex/com.android.runtime/bin/crash_dump64 ] && dump64=1\n"
    "printf 'trace_health %s %s %s\\n' \"$ready\" \"$running\" \"$dump64\"\n"
    "files=0; errors=0; limited=0\n"
    "for dir in /data/tombstones /data/anr /data/system/dropbox; do\n"
    "    if [ -L \"$dir\" ] || { [ -e \"$dir\" ] && { [ ! -d \"$dir\" ] || [ ! -r \"$dir\" ]; }; }; then errors=$((errors+1)); continue; fi\n"
    "    for file in \"$dir\"/*; do\n"
    "        [ ! -L \"$file\" ] && [ -f \"$file\" ] || continue\n"
    "        case \"$dir:${file##*/}\" in\n"
    "            /data/tombstones:tombstone_*.pb) continue;;\n"
    "            /data/tombstones:tombstone_*) kind=1;;\n"
    "            /data/anr:*) kind=2;;\n"
    "            /data/system/dropbox:system_server_crash@*.txt*) kind=3;;\n"
    "            /data/system/dropbox:data_app_crash@*.txt*|/data/system/dropbox:system_app_crash@*.txt*|/data/system/dropbox:app_crash@*.txt*) kind=4;;\n"
    "            *) continue;;\n"
    "        esac\n"
    "        files=$((files+1)); [ \"$files\" -le 64 ] || { limited=1; break; }\n"
    "        size=$(stat -c %s \"$file\" 2>/dev/null) || { errors=$((errors+1)); continue; }\n"
    "        case \"$size\" in ''|*[!0-9]*) errors=$((errors+1)); continue;; esac\n"
    "        cut=0; [ \"$size\" -le 65536 ] || cut=1\n"
    "        printf 'trace_begin %s %s %s %s\\n' \"$files\" \"$kind\" \"$size\" \"$cut\"\n"
    "        read_trace() {\n"
    "            case \"$file\" in *.gz) gzip -dc \"$file\" 2>/dev/null | head -c 65536;;\n"
    "                *) head -c 65536 \"$file\" 2>/dev/null;; esac\n"
    "        }\n"
    "        read_trace | awk '\n"
    "          {bytes+=length($0)+1}\n"
    "          function valid(s) {return s ~ /^[A-Za-z_][A-Za-z0-9_.:$<>-]*$/ && length(s)<=192}\n"
    "          function process_name(s) {return s ~ /^[A-Za-z_][A-Za-z0-9_.:@$<>-]*$/ && length(s)<=192 && s !~ /[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-/}\n"
    "          /^Cmd ?line:|^Process:/ {\n"
    "            name=$0; sub(/^[^:]*:[[:space:]]*/,\"\",name); sub(/[[:space:]].*$/,\"\",name); sub(/^.*\\//,\"\",name)\n"
    "            if(process_name(name) && sections++<16) print \"trace_section\",name; else name=\"\"\n"
    "          }\n"
    "          /^pid: .*>>> .* <<</ {\n"
    "            name=$0; sub(/^.*>>> /,\"\",name); sub(/ <<<.*$/,\"\",name); sub(/[[:space:]].*$/,\"\",name); sub(/^.*\\//,\"\",name)\n"
    "            if(process_name(name) && sections++<16) print \"trace_section\",name; else name=\"\"\n"
    "          }\n"
    "          /^signal [0-9]+ .*code -?[0-9]+/ {\n"
    "            sig=$2; code=$0; sub(/^.*code /,\"\",code); sub(/[^0-9-].*$/,\"\",code)\n"
    "            sig+=0; code+=0; if(sig>=1 && sig<=64 && code>=-255 && code<=255) print \"trace_signal\",sig+0,code+0\n"
    "          }\n"
    "          /^Abort message:/ {\n"
    "            cause=0; if(/fdsan/) cause=1; else if(/FORTIFY/) cause=2; else if(/assert|Assertion/) cause=3; else if(/Scudo/) cause=4\n"
    "            print \"trace_abort\",cause\n"
    "          }\n"
    "          /^[[:space:]]*#[0-9][0-9] pc / && frames<32 {\n"
    "            lib=$4; sub(/^.*\\//,\"\",lib); method=$5; sub(/^[(]/,\"\",method); sub(/[+)].*$/,\"\",method)\n"
    "            if(!valid(method)) method=\"unknown\"\n"
    "            if(valid(lib) && process_name(name)) {print \"trace_native\",lib,method; frames++}\n"
    "          }\n"
    "          /^[[:space:]]+at / && frames<32 {\n"
    "            method=$0; sub(/^[[:space:]]+at /,\"\",method); sub(/[(].*$/,\"\",method)\n"
    "            if(valid(method) && process_name(name)) {print \"trace_frame\",method; frames++}\n"
    "          }\n"
    "          /^[A-Za-z_][A-Za-z0-9_.$]*(Exception|Error)(:|$)/ {\n"
    "            exception=$0; sub(/:.*/,\"\",exception); if(valid(exception)) print \"trace_exception\",exception\n"
    "          }\n"
    "          END {print \"trace_prefix_limit\",(bytes>=65536)+0; print \"trace_frame_limit\",(frames>=32)+0}'\n"
    "        rc=$?\n"
    "        case \"$rc\" in 0) ;; 141) cut=1;; *) errors=$((errors+1));; esac\n"
    "        printf 'trace_end %s\\n' \"$rc\"\n"
    "    done\n"
    "    [ \"$limited\" = 0 ] || break\n"
    "done\n"
    "printf 'trace_files %s\\ntrace_errors %s\\ntrace_truncated %s\\n' \"$files\" \"$errors\" \"$limited\"\n"
;
