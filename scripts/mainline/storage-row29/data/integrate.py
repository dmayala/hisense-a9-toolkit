#!/usr/bin/env python3
"""Apply ROW29 or explicit RAM-data to a NEW vendor copy. Host-only; no boot edit.

Run last in an integrated vendor pipeline, after other feature/policy overlays.
Reads/writes regular image files only. Never follows an implicit data fallback.
"""
import argparse,hashlib,importlib.util,json,os,re,shutil,subprocess,tempfile
from pathlib import Path
HERE=Path(__file__).resolve().parent;REPO=HERE.parents[3]
DEFAULT_CACHE=Path.home()/'A9-build/mainline/android/cache/gsi-sepolicy/a9-los23.2-dozeoff-gapps-20260603-hwcguard-v8-3569860608-1792259254'
RAM='/dev/block/ram0 /data ext4 noatime,nosuid,nodev,discard wait,latemount,formattable'
ROW='/dev/block/mapper/a9-row29-data /data f2fs noatime,nosuid,nodev,nodiscard wait,latemount'
FBE=ROW+',fileencryption=aes-256-xts:aes-256-cts:v2'
SERVICE='''service a9ml_row29_map /vendor/bin/a9ml-row29-map
    disabled
    oneshot
    user root
    group root
    seclabel u:r:a9ml_row29_map:s0
'''
def sha(p):
    with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
def load(path,name):
    spec=importlib.util.spec_from_file_location(name,path);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m
def render(fstab,rc,mode):
    if mode not in ('row29','row29-fbe','ram'):raise ValueError('unknown data mode')
    lines=fstab.splitlines();data=[i for i,l in enumerate(lines) if l.split() and not l.lstrip().startswith('#') and len(l.split())>1 and l.split()[1]=='/data']
    if len(data)!=1 or lines[data[0]].split() not in (RAM.split(),ROW.split(),FBE.split()):raise ValueError('one known RAM/ROW29 /data row required; never replace another target')
    before=[l for l in lines if l.strip() and not l.lstrip().startswith('#') and l.split()[1]!='/data']
    lines[data[0]]={'row29':ROW,'row29-fbe':FBE,'ram':RAM}[mode]
    # Avoid stale RAM-only claims, retaining all actual first-stage rows.
    text='# B-only data mode: '+mode+'; generated by storage-row29/data/integrate.py\n'+'\n'.join(l for l in lines if l.strip() and not l.lstrip().startswith('#'))+'\n'
    assert [l for l in text.splitlines() if l and not l.startswith('#') and l.split()[1]!='/data']==before
    # Replace only our service block and our additions in the existing late-fs
    # action. Preserve all unrelated init services/actions/domain selections.
    rc=re.sub(r'^service a9ml_row29_map .*?(?=^(?:service |on |import )|\Z)','',rc,flags=re.M|re.S)
    actions=list(re.finditer(r'^on late-fs[^\n]*\n(?:(?!^(?:on |service |import )).)*',rc,flags=re.M|re.S))
    actions=[m for m in actions if 'mount_all /vendor/etc/fstab.hlte556n --late' in m[0]]
    if len(actions)!=1:raise ValueError('single existing late-fs mount_all action required')
    m=actions[0];block=m[0]
    block='\n'.join(l for l in block.split('\n') if not any(x in l for x in ('exec_start a9ml_row29_map','ROW29 DATA init: mapper exec_start','# Existing B-only diagnostic','# Existing f2fs only;','# Validate/map existing f2fs','# /data = /dev/block/ram0','# "nonencrypted" trigger')))
    mount='    mount_all /vendor/etc/fstab.hlte556n --late'
    if block.count(mount)!=1:raise ValueError('exact late mount_all required')
    if mode!='ram':
        if '    start a9ml_rootsh\n' not in block:block=block.replace(mount,'    start a9ml_rootsh\n'+mount)
        block=block.replace(mount,'    # Existing f2fs only; never mkfs/fallback at boot.\n    write /dev/kmsg "ROW29 DATA init: mapper exec_start"\n    exec_start a9ml_row29_map\n'+mount)
    rc=rc[:m.start()]+block+rc[m.end():]
    if mode!='ram':rc=rc.rstrip()+'\n\n'+SERVICE
    rc=re.sub(r'^# B-only data mode:.*\n','',rc,flags=re.M)
    rc='# B-only data mode: '+mode+'; mapper is never a boot formatter.\n'+rc
    rc=re.sub(r'write /dev/kmsg "a9ml: post-fs-data, /data (?:is RAM|mode (?:row29-fbe|row29|ram))"','write /dev/kmsg "a9ml: post-fs-data, /data mode '+mode+'"',rc)
    notes='''# ROW29 data notes begin
# B-only development vendor. PON beacon and original dead-man remain active.
# /metadata and /cache remain ephemeral; daily userdata/metadata/misc are absent
# from this fstab. Only row29 mode exposes the approved checked LUN4 extent RW.
# Existing f2fs is mandatory; boot never formats or falls back automatically.
# The helper clears the previous regular a9-stay before exposing persistent
# /data; the original keeper/timers still govern the current boot.
# Functional service domains are enforcing; a9ml_rootsh alone is permissive
# in the linked development policy. Incoming kernel cmdline mode is retained.
# ROW29 data notes end
'''
    rc=re.sub(r'^# ROW29 data notes begin\n.*?^# ROW29 data notes end\n','',rc,flags=re.M|re.S)
    rc=re.sub(r'^# Safety model \(details in the design report\):\n.*?^# they do not depend on this vendor\x27s policy\.\n','',rc,flags=re.M|re.S)
    rc=rc.replace('# (DRAFT 2026-10-15, not yet booted). Imported by the GSI\x27s init.rc line 10','# Imported by the GSI\x27s init.rc line 10')
    rc=rc.replace('# B-only data mode: '+mode+'; mapper is never a boot formatter.\n','# B-only data mode: '+mode+'; mapper is never a boot formatter.\n'+notes)
    rc=re.sub(r'^    # ROW29 FBE hold begin\n.*?^    # ROW29 FBE hold end\n','',rc,flags=re.M|re.S)
    if mode=='row29-fbe':
        if len(re.findall(r'^on init$',rc,flags=re.M))!=1:raise ValueError('single init action required for volatile hold')
        rc=rc.replace('on init\n','on init\n    # ROW29 FBE hold begin\n    mkdir /dev/a9-row29-hold 0770 shell shell\n    restorecon /dev/a9-row29-hold\n    # ROW29 FBE hold end\n')
        rc=rc.replace('# The helper clears the previous regular a9-stay before exposing persistent\n# /data; the original keeper/timers still govern the current boot.','# FBE hold is /dev/a9-row29-hold/stay (volatile); the mapper never traverses\n# encrypted directories before vold. Original keeper freshness/timers remain.')
        # No vendor /data children before the platform installkey/init_user0.
        # boot is queued after post-fs-data completes; adb USB starts there too.
        rc=rc.replace('\non post-fs-data\n','\n# ROW29 FBE auth: after platform installkey/init_user0\non boot\n')
    else:
        rc=rc.replace('\n# ROW29 FBE auth: after platform installkey/init_user0\non boot\n','\non post-fs-data\n')
    return text,rc
def compile_policy(base,out,cache,secilc,debug,fbe=False):
    sel=out/'selinux';debug(base,f'rdump /etc/selinux {out}')
    # rdump already populated selinux. Keep current base additions, append only
    # this feature. The precompiled binary and sidecars must agree with V8.
    cil=sel/'vendor_sepolicy.cil';text=cil.read_text()
    if '(type a9ml_row29_map)' not in text:text+='\n'+(HERE/'row29-map.cil').read_text()
    elif (HERE/'row29-map.cil').read_text().strip() not in text:raise ValueError('base has another ROW29 policy; update deliberately')
    if fbe and '(type a9ml_row29_hold_file)' not in text:text+='\n'+(HERE/'fbe/hold.cil').read_text()
    cil.write_text(text)
    fc=sel/'vendor_file_contexts';lines=fc.read_text().splitlines()
    additions=['/vendor/bin/a9ml-row29-map u:object_r:a9ml_row29_map_exec:s0','/dev/block/mapper/a9-row29-data u:object_r:dm_device:s0'];keys={l.split()[0] for l in additions}
    if fbe:
        additions+=['/dev/a9-row29-hold(/.*)? u:object_r:a9ml_row29_hold_file:s0'];keys.add('/dev/a9-row29-hold(/.*)?')
    fc.write_text('\n'.join(l for l in lines if not l or l.startswith('#') or l.split()[0] not in keys)+'\n'+'\n'.join(additions)+'\n')
    version=(sel/'plat_sepolicy_vers.txt').read_text().strip();system=cache/'system';plat=system/'etc/selinux'
    files=[plat/'plat_sepolicy.cil',plat/f'mapping/{version}.cil']
    for p in (plat/f'mapping/{version}.compat.cil',system/'system_ext/etc/selinux/system_ext_sepolicy.cil',system/f'system_ext/etc/selinux/mapping/{version}.cil',system/f'system_ext/etc/selinux/mapping/{version}.compat.cil',system/'product/etc/selinux/product_sepolicy.cil',system/f'product/etc/selinux/mapping/{version}.cil'):
        if p.is_file():files.append(p)
    files += [sel/'plat_pub_versioned.cil',cil]
    if (sel/'odm_sepolicy.cil').is_file():files.append(sel/'odm_sepolicy.cil')
    inputs=out/'policy-inputs';inputs.mkdir();private=[]
    for i,p in enumerate(files):
        text=p.read_text();text=re.sub(r'\(typepermissive ([^\s)]+)\)',lambda m:m[0] if m[1]=='a9ml_rootsh' else '',text)
        q=inputs/(str(i)+'-'+p.name);q.write_text(text);private.append(q)
    binary=sel/'precompiled_sepolicy'
    cmd=[str(secilc),'-D','-m','-M','true','-G','-N','-c','30',*map(str,private),'-o',str(binary),'-f','/dev/null']
    r=subprocess.run(cmd,capture_output=True);(out/'policy.log').write_bytes(r.stdout+r.stderr);r.check_returncode()
    for prefix,directory in [('plat',plat),('system_ext',system/'system_ext/etc/selinux'),('product',system/'product/etc/selinux')]:
        src=directory/(prefix+'_sepolicy_and_mapping.sha256')
        if src.exists():shutil.copyfile(src,sel/('precompiled_sepolicy.'+src.name))
    (out/'policy-command.json').write_text(json.dumps(cmd,indent=2)+'\n')
    return {str(p.relative_to(out)):p for p in sel.iterdir() if p.is_file() and (p.name in ('vendor_sepolicy.cil','vendor_file_contexts','precompiled_sepolicy') or p.name.startswith('precompiled_sepolicy.'))}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--base-vendor',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--data-mode',choices=('row29','row29-fbe','ram'),default='row29');p.add_argument('--kernel-config',type=Path);p.add_argument('--platform-cache',type=Path,default=DEFAULT_CACHE);p.add_argument('--secilc',type=Path,default=Path.home()/'A9-build/mainline/android/dl/cf_arm64_x/otatools/bin/secilc');a=p.parse_args()
    os.umask(0o077);out=a.out.resolve();base=a.base_vendor.resolve()
    if not base.is_file() or base.is_block_device() or not str(base).endswith('.img'):p.error('regular source vendor image required')
    out.mkdir(parents=True,exist_ok=True);image=out/'vendor.img'
    if image.exists() or image==base:p.error('fresh output directory required')
    if shutil.disk_usage(out).free-base.stat().st_size<2*1024**3:raise RuntimeError('preserve2GiB reserve')
    if a.data_mode!='ram' and a.kernel_config:
        config=a.kernel_config.read_text().splitlines()
        for name in ('BLK_DEV_DM','F2FS_FS','F2FS_FS_SECURITY'):
            if 'CONFIG_'+name+'=y' not in config:raise ValueError('ROW29 boot requires built-in CONFIG_'+name)
        if a.data_mode=='row29-fbe':
            for name in ('FS_ENCRYPTION','CRYPTO_AES','CRYPTO_XTS','CRYPTO_CTS','CRYPTO_SHA256'):
                if 'CONFIG_'+name+'=y' not in config:raise ValueError('software FBE requires built-in CONFIG_'+name)
    refresh=load(REPO/'scripts/mainline/android/refresh-integrated-vendor.py','row29_refresh');read=lambda path:refresh.debug(base,'cat /'+path)
    fstab,rc=render(read('etc/fstab.hlte556n'),read('etc/init/hw/init.hlte556n.rc'),a.data_mode)
    payload={};f=out/'fstab.hlte556n';f.write_text(fstab);payload['etc/fstab.hlte556n']=f;r=out/'init.hlte556n.rc';r.write_text(rc);payload['etc/init/hw/init.hlte556n.rc']=r
    if a.data_mode!='ram':
        helper=load(HERE/'build-map.py','row29_build').build(out/'native',fbe=a.data_mode=='row29-fbe');payload['bin/a9ml-row29-map']=helper
        payload.update({'etc/'+k:v for k,v in compile_policy(base,out,a.platform_cache,a.secilc,refresh.debug,a.data_mode=='row29-fbe').items()})
    for name in ('a9ml-deadman.sh','a9ml-ctl.sh'):
        original=read('bin/'+name)
        wanted='/dev/a9-row29-hold/stay' if a.data_mode=='row29-fbe' else '/data/local/tmp/a9-stay'
        script,count=re.subn(r'^STAY=(?:/data/local/tmp/a9-stay|/dev/a9-row29-hold/stay)$','STAY='+wanted,original,flags=re.M)
        if count!=1:raise ValueError('unknown hold contract: '+name)
        if a.data_mode=='row29-fbe':script=script.replace('# /data/local/tmp/a9-stay (RAM disk, gone at reboot) holds either phase while','# /dev/a9-row29-hold/stay (volatile /dev, gone at reboot) holds either phase while')
        if script!=original:
            q=out/name;q.write_text(script);payload['bin/'+name]=q
    batch=[];meta={}
    for i,(path,src) in enumerate(payload.items()):
        present='Inode:' in refresh.debug(base,'stat /'+path)
        m=refresh.metadata(base,path if present else 'etc/fstab.hlte556n')
        if path=='bin/a9ml-row29-map':m={**m,'mode':'0755','uid':'0','gid':'0','label':'u:object_r:a9ml_row29_map_exec:s0'}
        label=out/('label-'+str(i));label.write_bytes(m['label'].encode()+b'\0')
        if present:batch.append('rm /'+path)
        batch += [f'write {src} /{path}',f'sif /{path} mode 010{m["mode"]}',f'sif /{path} uid {m["uid"]}',f'sif /{path} gid {m["gid"]}',f'ea_set -f {label} /{path} security.selinux']
        for field in ('atime','mtime','ctime','crtime'):batch.append(f'sif /{path} {field} @{int(m[field],16)}')
        meta[path]=m
    subprocess.run(['cp','--reflink=auto','--sparse=always',str(base),str(image)],check=True);image.chmod(0o600);commands=out/'apply.debugfs';commands.write_text('\n'.join(batch)+'\n')
    with (out/'apply.log').open('w') as log:subprocess.run(['debugfs','-w','-f',str(commands),str(image)],check=True,stdout=log,stderr=subprocess.STDOUT)
    for path,src in payload.items():
        q=out/'readback';refresh.debug(image,f'dump /{path} {q}')
        if q.read_bytes()!=src.read_bytes() or refresh.metadata(image,path)!=meta[path]:raise ValueError('readback mismatch: '+path)
    with (out/'fsck.log').open('w') as log:subprocess.run(['e2fsck','-fn',str(image)],check=True,stdout=log,stderr=subprocess.STDOUT)
    assert image.stat().st_size==base.stat().st_size
    digest=sha(image);(out/'vendor.img.sha256').write_text(digest+'  '+str(image)+'\n')
    result={'base':str(base),'base_sha256':sha(base),'sha256':digest,'data_mode':a.data_mode,'changed':{k:sha(v) for k,v in payload.items()},'boot_changed':False,'phone_access':False,'free_bytes':shutil.disk_usage(out).free}
    assert result['free_bytes']>2*1024**3
    (out/'build-result.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result,indent=2))
if __name__=='__main__':main()
